"""Markdown report for a STRIKE Threat assessment."""

from __future__ import annotations

from strike.catalog import ATTACK_TECHNIQUES, STRIDE_CATEGORIES, tactic_name
from strike.engine import AssessmentResult


def _stride(ids: list[str]) -> str:
    lookup = {c["id"]: c["name"] for c in STRIDE_CATEGORIES}
    return ", ".join(lookup.get(i, i) for i in ids) or "—"


def _tech(ids: list[str]) -> str:
    parts = []
    for tid in ids:
        meta = ATTACK_TECHNIQUES.get(tid)
        if meta:
            parts.append(f"{tid} {meta['name']} ({tactic_name(meta['tactic'])})")
        else:
            parts.append(tid)
    return ", ".join(parts) or "—"


def render_markdown(result: AssessmentResult) -> str:
    lines: list[str] = [
        f"# STRIKE RA — {result.title}",
        "",
        "Threat-led risk assessment generated by **STRIKE Threat** "
        "(advanced threat modelling and intelligence).",
        "",
        f"**Aligned methodologies:** {', '.join(result.methodology_names)}",
        "",
        "## STRIKE answers",
        "",
    ]
    labels = {
        "S": "Scope",
        "T": "Threat",
        "R": "Route",
        "I": "Impact",
        "K": "Keep operating",
        "E": "Execute",
    }
    for letter, name in labels.items():
        answer = result.answers.get(letter) or "*(no answer)*"
        lines.extend([f"### {letter} — {name}", "", answer, ""])

    lines.extend(["## Crown jewels", ""])
    for jewel in result.crown_jewels:
        lines.append(f"- **{jewel.id} {jewel.name}** — {jewel.rationale} _(source: {jewel.source})_")
    lines.append("")

    lines.extend(["## Top threats", ""])
    for threat in result.threats:
        lines.append(f"### {threat.id} {threat.name}")
        lines.append("")
        lines.append(threat.description)
        lines.append("")
        lines.append(f"- Severity: {threat.severity}")
        lines.append(f"- STRIDE: {_stride(threat.stride)}")
        lines.append(f"- ATT&CK: {_tech(threat.attack_techniques)}")
        if threat.linddun:
            lines.append(f"- LINDDUN: {', '.join(threat.linddun)}")
        lines.append(f"- Centurion risk origin: {threat.risk_origin}")
        lines.append("")

    lines.extend(["## Attack paths", ""])
    for path in result.attack_paths:
        lines.append(f"### {path.id} {path.name}")
        lines.append("")
        for i, step in enumerate(path.steps, start=1):
            lines.append(f"{i}. {step}")
        lines.append("")
        lines.append(f"- Likelihood: {path.likelihood}")
        lines.append(f"- Techniques: {_tech(path.techniques)}")
        lines.append("")

    lines.extend(["## Ranked risk", "", "| ID | Scenario | Impact | Likelihood | Score |", "|----|----------|--------|------------|-------|"])
    for risk in result.ranked_risks:
        lines.append(
            f"| {risk.id} | {risk.title} | {risk.impact} | {risk.likelihood} | {risk.score} |"
        )
        if risk.dread:
            d = risk.dread
            lines.append(
                f"|  | DREAD D{d['damage']}/R{d['reproducibility']}/"
                f"E{d['exploitability']}/A{d['affected_users']}/"
                f"D{d['discoverability']} (total {d['total']}) |  |  |  |"
            )
    lines.extend(["", "## Resilience priorities", ""])
    for item in result.resilience:
        lines.append(f"- **{item.title}** ({item.csf_function}) — {item.action}")
    lines.extend(["", "## Action plan", ""])
    for item in result.action_plan:
        related = ", ".join(item.related_risk_ids) or "—"
        lines.append(f"1. **{item.title}** — owner hint: {item.owner_hint}; relates to {related}")
    lines.extend(["", "## Methodology alignment", "", "| STRIKE | Artefact | Aligns with |", "|--------|----------|-------------|"])
    for row in result.alignment:
        lines.append(f"| {row['letter']} {row['step']} | {row['artefact']} | {row['aligned_with']} |")
    if result.notes:
        lines.extend(["", f"_{result.notes}_"])
    lines.extend(
        [
            "",
            "---",
            "Centurion export (`centurion.ebios.v1`) is available from the report page as JSON. "
            "It maps this assessment onto EBIOS RM study objects used by CISO Assistant.",
            "",
        ]
    )
    return "\n".join(lines)
